; Host-side regression harness for the actual AT+CWLAP parser used by NETCFG's
; Wi-Fi scan wizard (src/lib/netcfg_scan.asm). Run through
; tools/test-netcfg-scan.sh.

	DEVICE NOSLOT64K

	INCLUDE "macro.inc"
	INCLUDE "dss.inc"

RS_BUFF_SIZE	EQU 2048
MAX_BUFF_SIZE	EQU 16384

TEST_RESULT	EQU 0xC000
RESP_BUF	EQU 0xC400		; stand-in for WIFI.RS_BUFF
CFG_SSID_BUF	EQU 0xCE00		; stand-in for NETCFG.CFG_SSID (33 bytes)
CFG_PASS_BUF	EQU 0xCE40		; stand-in for NETCFG.CFG_PASS

	ORG 0x4000

TEST_START
	XOR	A
	LD	(TEST_RESULT),A
	LD	(CHECKPOINT),A

	; ---- (a) mask-23 short form, one hidden AP ----
	LD	A,1
	LD	(CHECKPOINT),A
	LD	HL,VEC_A
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	JP	C,FAILED				; two records: no cap
	CP	2
	JP	NZ,FAILED
	LD	A,11
	LD	(CHECKPOINT),A
	LD	A,1
	CALL	MAIN.CWLAP_FIND
	JP	C,FAILED
	LD	A,12
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_ECN)
	AND	A
	JP	NZ,FAILED
	LD	A,13
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_RSSI)
	CP	45
	JP	NZ,FAILED
	LD	A,14
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_RSSI_NEG)
	CP	1
	JP	NZ,FAILED
	LD	A,15
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_CHAN)
	CP	6
	JP	NZ,FAILED
	LD	A,16
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_SSID_LEN)
	CP	6
	JP	NZ,FAILED
	LD	A,17
	LD	(CHECKPOINT),A
	LD	HL,(MAIN.AP_SSID)
	LD	DE,SSID_HOME5G
	LD	B,6
	CALL	CMP_MEM_STR
	JP	NZ,FAILED
	; the second visible record is "Office Wifi" (the hidden "" AP is skipped)
	LD	A,18
	LD	(CHECKPOINT),A
	LD	A,2
	CALL	MAIN.CWLAP_FIND
	JP	C,FAILED
	LD	A,19
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_ECN)
	CP	4
	JP	NZ,FAILED
	LD	A,20
	LD	(CHECKPOINT),A
	LD	A,(MAIN.AP_CHAN)
	CP	11
	JP	NZ,FAILED

	; ---- (b) jesperl real-firmware form + whitespace-only junk line ----
	LD	A,2
	LD	(CHECKPOINT),A
	LD	HL,VEC_B
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	CP	2
	JP	NZ,FAILED
	LD	A,1
	CALL	MAIN.CWLAP_FIND
	JP	C,FAILED
	LD	A,(MAIN.AP_ECN)
	CP	3
	JP	NZ,FAILED
	LD	A,(MAIN.AP_CHAN)
	CP	1
	JP	NZ,FAILED
	LD	A,(MAIN.AP_RSSI)
	CP	55
	JP	NZ,FAILED
	LD	A,(MAIN.AP_RSSI_NEG)
	CP	1
	JP	NZ,FAILED

	; ---- (c) SSID copy/truncation to CWLAP_SSID_MAX (32) bytes ----
	LD	A,3
	LD	(CHECKPOINT),A
	LD	HL,VEC_C1
	CALL	LOAD_RESP
	CALL	FILL_SSID_A5
	LD	A,1
	CALL	MAIN.CWLAP_APPLY_CHOICE
	JP	C,FAILED
	LD	HL,CFG_SSID_BUF
	LD	DE,SSID_32A
	LD	B,32
	CALL	CMP_MEM_STR
	JP	NZ,FAILED
	LD	A,(CFG_SSID_BUF+32)
	AND	A
	JP	NZ,FAILED

	LD	HL,VEC_C2
	CALL	LOAD_RESP
	CALL	FILL_SSID_A5
	LD	A,1
	CALL	MAIN.CWLAP_APPLY_CHOICE
	JP	C,FAILED
	LD	HL,CFG_SSID_BUF
	LD	DE,SSID_40B
	LD	B,32
	CALL	CMP_MEM_STR
	JP	NZ,FAILED
	LD	A,(CFG_SSID_BUF+32)
	AND	A
	JP	NZ,FAILED

	; ---- (d) 25 records cap at CWLAP_MAX_LIST (20) and report it (CF=1);
	;          FIND(21) misses ----
	LD	A,4
	LD	(CHECKPOINT),A
	LD	HL,VEC_D
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	JP	NC,FAILED				; the cap must be reported
	CP	20
	JP	NZ,FAILED
	LD	A,21
	CALL	MAIN.CWLAP_FIND
	JP	NC,FAILED

	; ---- (e) only OK / junk - no records ----
	LD	A,5
	LD	(CHECKPOINT),A
	LD	HL,VEC_E
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	AND	A
	JP	NZ,FAILED

	; ---- (f) APPLY_CHOICE + SECURITY_NAME ----
	LD	A,6
	LD	(CHECKPOINT),A
	LD	HL,VEC_F
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	JP	C,FAILED				; exactly two records: no cap
	CALL	FILL_PASS_A5
	LD	A,2					; record 2: ecn=0 (open), "SecondOpen"
	CALL	MAIN.CWLAP_APPLY_CHOICE
	JP	C,FAILED
	AND	A
	JP	NZ,FAILED
	LD	HL,CFG_SSID_BUF
	LD	DE,SSID_SECONDOPEN
	LD	B,SSID_SECONDOPEN_LEN
	CALL	CMP_MEM_STR
	JP	NZ,FAILED
	LD	A,(CFG_PASS_BUF)
	AND	A
	JP	NZ,FAILED

	CALL	FILL_PASS_A5
	LD	A,1					; record 1: ecn=3, "First"
	CALL	MAIN.CWLAP_APPLY_CHOICE
	JP	C,FAILED
	CP	3
	JP	NZ,FAILED
	LD	A,(CFG_PASS_BUF)
	CP	0xA5
	JP	NZ,FAILED				; non-open choice must not touch CFG_PASS

	XOR	A
	CALL	MAIN.CWLAP_SECURITY_NAME
	LD	DE,NAME_OPEN
	CALL	CMP_ASCIIZ
	JP	NZ,FAILED
	LD	A,3
	CALL	MAIN.CWLAP_SECURITY_NAME
	LD	DE,NAME_WPA2
	CALL	CMP_ASCIIZ
	JP	NZ,FAILED
	LD	A,7
	CALL	MAIN.CWLAP_SECURITY_NAME
	LD	DE,NAME_WPA2_WPA3
	CALL	CMP_ASCIIZ
	JP	NZ,FAILED
	LD	A,9
	CALL	MAIN.CWLAP_SECURITY_NAME
	LD	DE,NAME_UNKNOWN
	CALL	CMP_ASCIIZ
	JP	NZ,FAILED

	; ---- (g) rssi without '-'; '"' inside SSID must not hang the parser ----
	LD	A,7
	LD	(CHECKPOINT),A
	LD	HL,VEC_G1
	CALL	LOAD_RESP
	LD	A,1
	CALL	MAIN.CWLAP_FIND
	JP	C,FAILED
	LD	A,(MAIN.AP_RSSI_NEG)
	AND	A
	JP	NZ,FAILED
	LD	A,(MAIN.AP_RSSI)
	CP	45
	JP	NZ,FAILED

	LD	HL,VEC_G2
	CALL	LOAD_RESP
	CALL	MAIN.CWLAP_COUNT
	AND	A
	JP	NZ,FAILED

	JR	TEST_DONE

FAILED
	LD	A,(CHECKPOINT)
	AND	A
	JR	NZ,.HAVE_CP
	LD	A,0xFF
.HAVE_CP
	LD	(TEST_RESULT),A
TEST_DONE
	HALT

; ------------------------------------------------------
; Helpers
; ------------------------------------------------------

; In: HL = source (embedded LF as 10, NUL terminated). Copies through the
; terminating NUL into RESP_BUF, exactly as WIFI.UART_TX_CMD leaves it.
LOAD_RESP
	PUSH	HL,DE
	LD	DE,RESP_BUF
.LOOP
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	AND	A
	JR	NZ,.LOOP
	POP	DE,HL
	RET

FILL_SSID_A5
	PUSH	HL,DE,BC
	LD	HL,CFG_SSID_BUF
	LD	DE,CFG_SSID_BUF+1
	LD	BC,33-1
	LD	(HL),0xA5
	LDIR
	POP	BC,DE,HL
	RET

FILL_PASS_A5
	PUSH	HL,DE,BC
	LD	HL,CFG_PASS_BUF
	LD	DE,CFG_PASS_BUF+1
	LD	BC,8-1
	LD	(HL),0xA5
	LDIR
	POP	BC,DE,HL
	RET

; Compare B raw bytes at HL against DE (no terminator check).
; Out: ZF=1 - equal.
CMP_MEM_STR
	PUSH	HL,DE,BC
.LOOP
	LD	A,(DE)
	CP	(HL)
	JR	NZ,.DONE
	INC	HL
	INC	DE
	DJNZ	.LOOP
.DONE
	POP	BC,DE,HL
	RET

; Compare ASCIIZ strings at HL, DE. Out: ZF=1 - equal.
CMP_ASCIIZ
	PUSH	HL,DE
.LOOP
	LD	A,(DE)
	CP	(HL)
	JR	NZ,.DONE
	AND	A
	JR	Z,.DONE
	INC	HL
	INC	DE
	JR	.LOOP
.DONE
	POP	DE,HL
	RET

CHECKPOINT	DB 0

SSID_HOME5G		DB "Home5G"
SSID_32A		DB "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"
SSID_40B		DB "BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
SSID_SECONDOPEN		DB "SecondOpen",0
SSID_SECONDOPEN_LEN	EQU $-SSID_SECONDOPEN-1

NAME_OPEN		DB "Open",0
NAME_WPA2		DB "WPA2",0
NAME_WPA2_WPA3		DB "WPA2/WPA3",0
NAME_UNKNOWN		DB "?",0

VEC_A
	DB	'+CWLAP:(0,"Home5G",-45,6)',10
	DB	'+CWLAP:(0,"",-70,6)',10
	DB	'+CWLAP:(4,"Office Wifi",-60,11)',10
	DB	"OK",0

VEC_B
	DB	'+CWLAP: (3,"ANOTHERWLAN",-55,"34:2c:c4:02:01:02",1,-22,0,4,4,7,1)',10
	DB	'                                       ',10
	DB	'+CWLAP: (3,"JESPERLNET",-5,"34:2c:c4:01:02:01",1,-22,0,4,4,7,0)',10
	DB	"OK",0

VEC_C1
	DB	'+CWLAP:(3,"AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA",-40,1)',10
	DB	"OK",0

VEC_C2
	DB	'+CWLAP:(3,"BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB",-40,1)',10
	DB	"OK",0

VEC_D
	DUP	25
	DB	'+CWLAP:(0,"N",-50,1)',10
	EDUP
	DB	"OK",0

VEC_E
	DB	"OK",0

VEC_F
	DB	'+CWLAP:(3,"First",-40,1)',10
	DB	'+CWLAP:(0,"SecondOpen",-50,6)',10
	DB	"OK",0

VEC_G1
	DB	'+CWLAP:(0,"Positive",45,6)',10
	DB	"OK",0

VEC_G2
	DB	'+CWLAP:(0,"Bad"Name",-40,1)',0

	MODULE WIFI
RS_BUFF	EQU RESP_BUF
	ENDMODULE

	MODULE NETCFG
CFG_SSID	EQU CFG_SSID_BUF
CFG_PASS	EQU CFG_PASS_BUF
