	; The session was synchronised, cleaned and put in CIPMUX=0 immediately
	; above. Do not repeat that whole command sequence here: duplicate cleanup
	; can collide with asynchronous CLOSED/ERROR tails and manufacture RES_BUSY.
	PUSH	HL
	LD	HL,0
	LD	(TCP.PAYLOAD_LEFT),HL
	XOR	A
	LD	(TCP.LSR_ACCUM),A
	CALL	WIFI.UART_RX_RESUME
	CALL	WIFI.UART_EMPTY_RS
	POP	HL
	; TCP.OPEN already has its own bounded busy-p retry loop. A second blind
	; CIPSTART after refusal/timeout can race the first pending connect and turn
	; the useful original result into a misleading RES_BUSY (#9).
	JP	TCP.OPEN

