; SprinterESP board diagnosis. No ESP commands or implicit hardware reset.
; Select the physical ISA slot explicitly so BUS also works with a dead UART.
EXE_VERSION	EQU 1
DEFAULT_TIMEOUT	EQU 2000

	DEVICE NOSLOT64K
	INCLUDE "macro.inc"
	INCLUDE "dss.inc"

	MODULE MAIN
LOAD_ADDR	EQU 0x8100
CMDLINE_ADDR	EQU LOAD_ADDR-0x80
STACK_TOP	EQU LOAD_ADDR
	ORG LOAD_ADDR-0x200
	DB "EXE",EXE_VERSION
	DW 0x200,0,0,0,0,0,START,START,STACK_TOP
	DS 490,0
	ORG LOAD_ADDR
START
	LD	(CMDLINE_PTR),IX
	CALL	WCOMMON.INIT_VMODE
	PRINTLN MSG_START
	CALL	PARSE
	JP	C,USAGE
	LD	A,(ISA.ISA_SLOT)
	ADD	A,'1'
	LD	(MSG_SLOT_NO),A
	PRINTLN MSG_SLOT
	PRINTLN MSG_WARNING
	LD	A,(MODE)
	CP	'B'
	JP	Z,BUS_MODE

	; SCR alone does not require a running UART oscillator or ESP firmware.
	PRINT MSG_SCR
	LD	HL,REG_SCR
	CALL	WIFI.UART_READ
	LD	(SAVED_SCR),A
	LD	E,0
.SCR_NEXT
	CALL	CHECK_REG
	JR	NZ,.SCR_FAIL
	INC	E
	JR	NZ,.SCR_NEXT
	LD	A,(SAVED_SCR)
	LD	E,A
	CALL	WIFI.UART_WRITE
	PRINTLN MSG_PASS
	CALL	INIT_UART
	LD	A,(MODE)
	CP	'T'
	JP	Z,TX_MODE
	CP	'R'
	JP	Z,RTS_MODE
	CALL	TEST_REGS
	CALL	TEST_MODEM
	CALL	TEST_SERIAL
	CALL	TEST_FIFO
	PRINTLN MSG_ALL_PASS
	JP	OK_EXIT
.SCR_FAIL
	CALL	PRINT_MISMATCH
	LD	A,(SAVED_SCR)
	LD	E,A
	LD	HL,REG_SCR
	CALL	WIFI.UART_WRITE
	LD	B,2
	JP	WCOMMON.EXIT

; Exactly two tokens: slot 1/2 and TEST/BUS/TX/RTS (case insensitive).
PARSE
	LD	HL,(CMDLINE_PTR)
	LD	B,(HL)
	INC	HL
	CALL	SKIP_SPACES
	RET	C
	LD	A,(HL)
	SUB	'1'
	CP	2
	CCF
	RET	C
	LD	(ISA.ISA_SLOT),A
	INC	HL
	DEC	B
	SCF
	RET	Z
	LD	A,(HL)
	CP	' '
	SCF
	RET	NZ
	CALL	SKIP_SPACES
	RET	C
	LD	DE,ARG_BUF
	LD	C,0
.COPY
	LD	A,(HL)
	CP	' '
	JR	Z,.END_TOKEN
	CP	'a'
	JR	C,.UPPER
	CP	'z'+1
	JR	NC,.UPPER
	AND	0xDF
.UPPER
	LD	(DE),A
	INC	DE
	INC	HL
	INC	C
	LD	A,C
	CP	5
	JR	C,.LEN_OK
	SCF
	RET
.LEN_OK
	DJNZ .COPY
.END_TOKEN
	XOR	A
	LD	(DE),A
.TAIL
	LD	A,B
	OR	A
	JR	Z,.MATCH
	LD	A,(HL)
	CP	' '
	SCF
	RET	NZ
	INC	HL
	DJNZ .TAIL
.MATCH
	LD	HL,ARG_BUF
	LD	DE,ARG_TEST
	CALL	UTIL.STRCMP
	LD	A,'C'
	JR	NC,.FOUND
	LD	DE,ARG_BUS
	CALL	UTIL.STRCMP
	LD	A,'B'
	JR	NC,.FOUND
	LD	DE,ARG_TX
	CALL	UTIL.STRCMP
	LD	A,'T'
	JR	NC,.FOUND
	LD	DE,ARG_RTS
	CALL	UTIL.STRCMP
	LD	A,'R'
	RET	C
.FOUND
	LD	(MODE),A
	OR	A
	RET
SKIP_SPACES
	LD	A,B
	OR	A
	SCF
	RET	Z
	LD	A,(HL)
	CP	' '
	RET	NZ			; CP non-space (ASCII >= 0x20) clears carry
	INC	HL
	DJNZ SKIP_SPACES
	SCF
	RET

INIT_UART
	LD	HL,REG_LCR
	LD	E,LCR_WL8
	CALL	WIFI.UART_WRITE
	LD	HL,REG_IER
	LD	E,0
	CALL	WIFI.UART_WRITE
	LD	HL,REG_MCR
	CALL	WIFI.UART_WRITE	; AFE off; OUT1/OUT2 high, RESET/PGM released
	LD	HL,REG_FCR
	LD	E,7
	CALL	WIFI.UART_WRITE
	LD	E,0
	CALL	WIFI.UART_WRITE
SET_BAUD
	LD	HL,REG_LCR
	LD	E,LCR_DLAB | LCR_WL8
	CALL	WIFI.UART_WRITE
	LD	HL,REG_DLL
	LD	E,8			; 14.7456 MHz / 8 / 16 = 115200
	CALL	WIFI.UART_WRITE
	INC	HL
	LD	E,0
	CALL	WIFI.UART_WRITE
	LD	HL,REG_LCR
	LD	E,LCR_WL8
	JP	WIFI.UART_WRITE

; Keep distinct values alive in adjacent registers to detect address aliasing.
TEST_REGS
	PRINT MSG_REGS
	LD	HL,REG_LCR
	LD	E,LCR_DLAB | LCR_WL8
	CALL	WIFI.UART_WRITE
	LD	HL,REG_DLL
	LD	E,0x55
	CALL	WIFI.UART_WRITE
	INC	HL
	LD	E,0xAA
	CALL	WIFI.UART_WRITE
	DEC	HL
	LD	E,0x55
	CALL	READ_CHECK
	INC	HL
	LD	E,0xAA
	CALL	READ_CHECK
	LD	HL,REG_LCR
	LD	E,LCR_WL8
	CALL	CHECK_OR_FAIL
	LD	HL,REG_IER
	; Compare the disabled IER with DLM=AA without briefly enabling IRQ3
	; while external ESP traffic may still be pending.
	LD	E,0
	CALL	CHECK_OR_FAIL
	LD	HL,REG_LCR
	LD	E,LCR_WL8
	CALL	READ_CHECK
	LD	HL,REG_IER
	LD	E,0
	CALL	CHECK_OR_FAIL
	CALL	SET_BAUD
	PRINTLN MSG_PASS
	RET

TEST_MODEM
	PRINT MSG_MODEM
	LD	D,0
.NEXT
	LD	HL,REG_MCR
	LD	A,D
	OR	MCR_LOOP
	LD	E,A
	CALL	WIFI.UART_WRITE
	CALL	READ_CHECK
	; MSR[7:4] = OUT2,OUT1,DTR,RTS; ignore delta bits [3:0].
	LD	A,D
	AND	0x0C
	LD	E,A
	LD	A,D
	AND	1
	ADD	A,A
	OR	E
	LD	E,A
	LD	A,D
	AND	2
	RRCA
	OR	E
	ADD	A,A
	ADD	A,A
	ADD	A,A
	ADD	A,A
	LD	E,A
	LD	HL,REG_MSR
	CALL	WIFI.UART_READ
	AND	0xF0
	CP	E
	JP	NZ,MISMATCH
	INC	D
	LD	A,D
	CP	16
	JR	NZ,.NEXT
	LD	HL,REG_MCR
	LD	E,MCR_LOOP
	CALL	WIFI.UART_WRITE
	PRINTLN MSG_PASS
	RET

TEST_SERIAL
	; LOOP disconnects external SIN, but entering LOOP does not clear a
	; character/error already latched from external traffic or floating SIN
	; (J2 disables D4). Let any partial character finish before establishing
	; the baseline. FIFO is disabled here, so RBR holds at most one byte.
	; Clear only this pre-test state; WAIT_RX still rejects every new error.
	LD	HL,10
	CALL	UTIL.DELAY
	LD	HL,REG_LSR
	CALL	WIFI.UART_READ
	LD	(STALE_LSR),A
	AND	LSR_DR
	JR	Z,.ACK_ERRORS
	LD	HL,REG_RBR
	CALL	WIFI.UART_READ
.ACK_ERRORS
	LD	HL,REG_LSR
	CALL	WIFI.UART_READ
	LD	A,(STALE_LSR)
	AND	0x1F
	JR	Z,.READY
	PRINT MSG_STALE_RX
	LD	A,(STALE_LSR)
	CALL	PRINT_HEX
	PRINTLN WCOMMON.LINE_END
.READY
	PRINT MSG_SERIAL
	LD	A,0
.NEXT
	LD	(EXPECTED),A
	CALL	WAIT_TX
	LD	A,(EXPECTED)
	LD	E,A
	LD	HL,REG_THR
	CALL	WIFI.UART_WRITE
	CALL	WAIT_RX
	LD	HL,REG_RBR
	LD	A,(EXPECTED)
	LD	E,A
	CALL	READ_CHECK
	LD	A,(EXPECTED)
	INC	A
	JR	NZ,.NEXT
	PRINTLN MSG_PASS
	RET

TEST_FIFO
	PRINT MSG_FIFO
	LD	HL,REG_FCR
	LD	E,7
	CALL	WIFI.UART_WRITE
	LD	HL,REG_IIR
	CALL	WIFI.UART_READ
	AND	0xC0
	LD	E,0xC0
	CP	E
	JP	NZ,MISMATCH
	LD	A,0
.SEND
	LD	(EXPECTED),A
	CALL	WAIT_TX
	LD	A,(EXPECTED)
	LD	E,A
	LD	HL,REG_THR
	CALL	WIFI.UART_WRITE
	; Wait per character, but leave all sixteen received bytes in RX FIFO.
	LD	HL,2
	CALL	UTIL.DELAY
	LD	A,(EXPECTED)
	INC	A
	CP	16
	JR	NZ,.SEND
	LD	A,0
.RECEIVE
	LD	(EXPECTED),A
	CALL	WAIT_RX
	LD	HL,REG_RBR
	LD	A,(EXPECTED)
	LD	E,A
	CALL	READ_CHECK
	LD	A,(EXPECTED)
	INC	A
	CP	16
	JR	NZ,.RECEIVE
	LD	HL,REG_LSR
	CALL	WIFI.UART_READ
	AND	LSR_DR | LSR_OE | LSR_PE | LSR_FE | LSR_BI | LSR_RCVE
	LD	E,0
	CP	E
	JP	NZ,MISMATCH
	PRINTLN MSG_PASS
	RET

; Scope modes run until Esc/Ctrl+Z. No DSS calls with ISA mapped.
BUS_MODE
	PRINTLN MSG_BUS
.NEXT
	LD	HL,REG_SCR
	LD	E,0x55
	CALL	WIFI.UART_WRITE
	CALL	WIFI.UART_READ
	LD	E,0xAA
	CALL	WIFI.UART_WRITE
	CALL	WIFI.UART_READ
	CALL	WCOMMON.CHECK_CANCEL
	JR	NC,.NEXT
	LD	B,0
	JP	WCOMMON.EXIT		; no UART setup/cleanup needed for BUS
TX_MODE
	PRINTLN MSG_TX
.NEXT
	CALL	WAIT_SCOPE_TX
	LD	HL,REG_THR
	LD	E,0x55
	CALL	WIFI.UART_WRITE
	CALL	WCOMMON.CHECK_CANCEL
	JR	NC,.NEXT
	JP	OK_EXIT
RTS_MODE
	PRINTLN MSG_RTS
.NEXT
	LD	HL,REG_MCR
	LD	E,MCR_RTS
	CALL	WIFI.UART_WRITE
	LD	HL,250
	CALL	UTIL.DELAY
	LD	HL,REG_MSR
	CALL	WIFI.UART_READ
	LD	(SAMPLE_LOW),A
	LD	HL,REG_MCR
	LD	E,0
	CALL	WIFI.UART_WRITE
	LD	HL,250
	CALL	UTIL.DELAY
	LD	HL,REG_MSR
	CALL	WIFI.UART_READ
	LD	(SAMPLE_HIGH),A
	PRINT MSG_CTS_LOW
	LD	A,(SAMPLE_LOW)
	CALL	PRINT_HEX
	PRINT MSG_CTS_HIGH
	LD	A,(SAMPLE_HIGH)
	CALL	PRINT_HEX
	PRINTLN WCOMMON.LINE_END
	CALL	WCOMMON.CHECK_CANCEL
	JR	NC,.NEXT
OK_EXIT
	CALL	CLEANUP
	PRINTLN MSG_REINIT
	LD	B,0
	JP	WCOMMON.EXIT
CLEANUP
	; Never restore arbitrary MCR bits: OUT1/OUT2 control reset/programming.
	LD	HL,REG_LCR
	LD	E,LCR_WL8
	CALL	WIFI.UART_WRITE
	LD	HL,REG_IER
	LD	E,0
	CALL	WIFI.UART_WRITE
	LD	HL,REG_MCR
	CALL	WIFI.UART_WRITE
	LD	HL,REG_FCR
	LD	E,7
	CALL	WIFI.UART_WRITE
	LD	E,0
	CALL	WIFI.UART_WRITE
	JP	SET_BAUD

; Scope TX must also work with the external receiver disconnected by J2.
; Floating SIN can set FE/BI/OE; these RX flags must not stop SOUT generation.
; Retain a bounded THRE wait so a stuck transmitter still reports failure.
; Internal loopback tests continue to use the strict WAIT_TX/WAIT_RX below.
WAIT_SCOPE_TX
	LD	BC,10000
.POLL
	LD	HL,REG_LSR
	CALL	WIFI.UART_READ
	LD	(LAST_LSR),A
	AND	LSR_THRE
	RET	NZ
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,.POLL
	JP	WAIT_LSR.TIMEOUT

WAIT_TX
	LD	D,LSR_THRE
	JR	WAIT_LSR
WAIT_RX
	LD	D,LSR_DR
WAIT_LSR
	LD	BC,10000
.POLL
	LD	HL,REG_LSR
	CALL	WIFI.UART_READ
	LD	(LAST_LSR),A
	AND	LSR_OE | LSR_PE | LSR_FE | LSR_BI | LSR_RCVE
	JP	NZ,LINE_ERROR
	LD	A,(LAST_LSR)
	AND	D
	RET	NZ
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,.POLL
.TIMEOUT
	PRINTLN MSG_TIMEOUT
	LD	A,(LAST_LSR)
	CALL	PRINT_HEX
	JP	FAIL_EXIT
LINE_ERROR
	PRINTLN MSG_LINE_ERROR
	LD	A,(LAST_LSR)
	CALL	PRINT_HEX
	JP	FAIL_EXIT
CHECK_OR_FAIL
	CALL	CHECK_REG
	RET	Z
	JP	MISMATCH
CHECK_REG
	CALL	WIFI.UART_WRITE
	CALL	WIFI.UART_READ
	CP	E
	RET
READ_CHECK
	CALL	WIFI.UART_READ
	CP	E
	RET	Z
	; READ_CHECK is also called directly by TEST routines.
MISMATCH
	CALL	PRINT_MISMATCH
FAIL_EXIT
	CALL	CLEANUP
	PRINTLN MSG_REINIT
	LD	B,3
	JP	WCOMMON.EXIT
PRINT_MISMATCH
	LD	(ACTUAL),A
	LD	A,E
	LD	(EXPECTED),A
	LD	(FAILED_REG),HL
	PRINT MSG_FAIL_REG
	LD	A,(FAILED_REG+1)
	CALL	PRINT_HEX
	LD	A,(FAILED_REG)
	CALL	PRINT_HEX
	PRINT MSG_EXPECTED
	LD	A,(EXPECTED)
	CALL	PRINT_HEX
	PRINT MSG_ACTUAL
	LD	A,(ACTUAL)
	CALL	PRINT_HEX
	PRINTLN WCOMMON.LINE_END
	RET
PRINT_HEX
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	.NIBBLE
	POP	AF
.NIBBLE
	AND	15
	ADD	A,'0'
	CP	'9'+1
	JR	C,.PUT
	ADD	A,7
.PUT
	PUSH	BC,DE,HL
	LD	C,DSS_PUTCHAR
	RST	DSS
	POP	HL,DE,BC
	RET
USAGE
	PRINTLN MSG_USAGE
	LD	B,1
	JP	WCOMMON.EXIT

MSG_START	DB "HWTEST ": PACKAGE_VERSION_TAG
	DB " rev.3 - SprinterESP hardware diagnosis",0
MSG_SLOT	DB "ISA slot "
MSG_SLOT_NO	DB "1, COM3 03E8-03EF",0
MSG_WARNING	DB "Bench test: local UART is changed; no ESP reset/AT commands.",0
MSG_USAGE	DB "Usage: HWTEST 1|2 TEST|BUS|TX|RTS",13,10
	DB "Scope modes: Esc/Ctrl+Z to stop. See HWTEST.TXT.",0
MSG_SCR	DB "SCR 00..FF: ",0
MSG_REGS	DB "DLL/DLM/IER/LCR address isolation: ",0
MSG_MODEM	DB "Internal MCR/MSR loop: ",0
MSG_SERIAL	DB "Internal serial loop 00..FF at 115200: ",0
MSG_STALE_RX	DB "Cleared pre-test RX state, LSR=",0
MSG_FIFO	DB "RX FIFO holds 16 bytes: ",0
MSG_PASS	DB "PASS",0
MSG_ALL_PASS	DB "UART tests PASS. External pins, D4 and ESP still need probing.",0
MSG_BUS	DB "BUS: SCR writes 55/AA and reads, even if no UART responds.",0
MSG_TX	DB "TX: repeated 55h at 115200 8N1, AFE off; RX errors ignored.",0
MSG_RTS	DB "RTS: toggling MCR bit 1, ~250 ms per level. MSR bit 4 is CTS.",0
MSG_CTS_LOW	DB "RTS low: MSR=",0
MSG_CTS_HIGH	DB "  RTS high: MSR=",0
MSG_TIMEOUT	DB "FAIL: LSR wait timed out. LSR=",0
MSG_LINE_ERROR	DB "FAIL: UART line/FIFO error. LSR=",0
MSG_FAIL_REG	DB "FAIL register ",0
MSG_EXPECTED	DB " expected=",0
MSG_ACTUAL	DB " actual=",0
MSG_REINIT	DB "Test ended. Power-cycle ESP after TX; run NETUP before networking.",0
ARG_TEST	DB "TEST",0
ARG_BUS	DB "BUS",0
ARG_TX	DB "TX",0
ARG_RTS	DB "RTS",0
CMDLINE_PTR	DW CMDLINE_ADDR
MODE		DB 0
SAVED_SCR	DB 0
EXPECTED	DB 0
ACTUAL		DB 0
FAILED_REG	DW 0
LAST_LSR	DB 0
STALE_LSR	DB 0
SAMPLE_LOW	DB 0
SAMPLE_HIGH	DB 0
ARG_BUF		DS 5,0
	ENDMODULE
	DEFINE WCOMMON_NO_INIT_ESP
	DEFINE ESPLIB_NO_RESET
	INCLUDE "wcommon.asm"
	INCLUDE "esplib.asm"
	ASSERT $ < 0xC000
	END MAIN.START
